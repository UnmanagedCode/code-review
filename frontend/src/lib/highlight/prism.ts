// Loaded lazily (useTokenizer in features/diff), so the main bundle carries no grammar. Only the data tokenizer is used:
// never Prism's highlight functions, which build markup.

export type PrismToken = string | Prism.Token;

/** `text` as Prism's token tree; a language Prism lacks yields the text as one plain string. */
export function tokenize(text: string, lang: string): PrismToken[] {
  const grammar = Prism.languages[lang];
  return grammar ? Prism.tokenize(text, grammar) : [text];
}
